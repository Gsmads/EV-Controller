/**
 * @file util_ring.h
 * @brief Кольцевой буфер байтов без динамической памяти
 *
 * Переносимый модуль: платформы не знает, собирается и проверяется на
 * десктопе. Введён решением ADR-0018 вместо MICRO_UART, который обращался
 * к регистрам ATmega328P вне hal_atmega328p.cpp и потому был непроверяем.
 *
 * Используется под буферы приёма и передачи UART. Работа с регистрами,
 * обработчики прерываний и делитель скорости остаются в hal_atmega328p.cpp.
 *
 * ПОЧЕМУ ИНДЕКСЫ ВОСЬМИБИТНЫЕ. Один индекс пишется обработчиком прерывания,
 * другой — основным кодом. На AVR чтение и запись uint8_t выполняются одной
 * инструкцией, то есть атомарны; uint16_t прерывание может разорвать между
 * байтами и дать значение, которого никогда не было. Отсюда предел ёмкости —
 * 254 полезных байта. Для пакета телеметрии в 41 байт запас четырёхкратный.
 *
 * ПОЧЕМУ ЁМКОСТЬ НА ЕДИНИЦУ МЕНЬШЕ ХРАНИЛИЩА. Различить пустое и полное
 * кольцо при head == tail нельзя, поэтому одна ячейка не используется:
 * при хранилище size полезных байт — size-1.
 *
 * ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ:
 *   - не ждёт освобождения места. Режим TX_OVERFLOW_BLOCK из ADR-0016 —
 *     ожидание готовности регистра UDRE, то есть работа с железом, и живёт
 *     в HAL. Здесь только режим "не влезло — не записали";
 *   - не запрещает прерывания. Атомарность держится на восьмибитных
 *     индексах, а не на критических секциях;
 *   - не знает про пакеты. util_ring_put_all() отвечает на вопрос
 *     "влезает ли блок целиком", а границы кадра задаёт вызывающий.
 */
#pragma once

#include <stdint.h>

/**
 * @brief Состояние кольцевого буфера
 *
 * Хранилище принадлежит вызывающему: модуль ничего не выделяет
 * (CLAUDE.md §3 правило 5 — динамическая память запрещена).
 */
typedef struct {
    uint8_t          *buf;      /**< Хранилище, принадлежит вызывающему */
    uint8_t           size;     /**< Размер хранилища; полезная ёмкость size-1 */
    volatile uint8_t  head;     /**< Куда писать следующий байт */
    volatile uint8_t  tail;     /**< Откуда читать следующий байт */
    uint16_t          dropped;  /**< Сколько блоков отвергнуто целиком */
} util_ring_t;

/**
 * @brief Инициализация кольца
 * @param r       Кольцо
 * @param storage Хранилище вызывающего, не менее size байт
 * @param size    Размер хранилища (2…255); полезная ёмкость будет size-1
 */
void util_ring_init(util_ring_t *r, uint8_t *storage, uint8_t size);

/**
 * @brief Сброс: кольцо становится пустым, счётчик потерь обнуляется
 * @param r Кольцо
 */
void util_ring_reset(util_ring_t *r);

/**
 * @brief Сколько байт лежит в кольце
 * @param r Кольцо
 * @return Занято байт, 0…size-1
 */
uint8_t util_ring_count(const util_ring_t *r);

/**
 * @brief Сколько байт ещё поместится
 * @param r Кольцо
 * @return Свободно байт, 0…size-1
 */
uint8_t util_ring_free(const util_ring_t *r);

/**
 * @brief Пусто ли кольцо
 * @param r Кольцо
 * @return 1 — пусто, 0 — нет
 */
uint8_t util_ring_is_empty(const util_ring_t *r);

/**
 * @brief Записать один байт
 * @param r Кольцо
 * @param b Байт
 * @return 1 — записан, 0 — места не было и ничего не изменилось
 */
uint8_t util_ring_put(util_ring_t *r, uint8_t b);

/**
 * @brief Записать блок целиком или не записать ничего
 *
 * Режим TX_OVERFLOW_DROP_PACKET из ADR-0016: усечённый пакет ушёл бы в линию
 * валидным по длине, и мост увидел бы битый CRC, не отличив его от помехи.
 * Поэтому блок либо помещается целиком, либо отвергается весь, а отказ
 * попадает в счётчик — у отказа должно быть имя (CONVENTIONS.md §10).
 *
 * @param r    Кольцо
 * @param data Блок
 * @param len  Длина блока
 * @return 1 — записан целиком, 0 — отвергнут целиком, счётчик потерь вырос
 */
uint8_t util_ring_put_all(util_ring_t *r, const uint8_t *data, uint8_t len);

/**
 * @brief Прочитать один байт
 *
 * Возвращает int16_t, а не uint8_t, именно ради дефекта B-2 docs/AUDIT.md:
 * унаследованный из Grbl признак пустоты SERIAL_NO_DATA = 0xFF в бинарном
 * протоколе является обычным байтом данных. Отрицательное значение
 * непредставимо в данных и потому однозначно.
 *
 * @param r Кольцо
 * @return Байт 0…255, либо -1 если кольцо пусто
 */
int16_t util_ring_get(util_ring_t *r);

/**
 * @brief Сколько блоков было отвергнуто целиком с момента сброса
 *
 * Уходит в телеметрию как uart_tx_dropped (ADR-0016).
 *
 * @param r Кольцо
 * @return Число отказов; при переполнении счётчика остаётся на 65535
 */
uint16_t util_ring_dropped(const util_ring_t *r);
