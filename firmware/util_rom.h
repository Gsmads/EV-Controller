/**
 * @file util_rom.h
 * @brief Постоянное хранение: таблицы и строки, известные на этапе сборки
 *
 * Решение ADR-0021. Программа различает два вида хранения по назначению,
 * а не по технологии:
 *
 *   постоянное     — неизменяемые таблицы и строки. Этот файл.
 *                    На ATmega328P лежит во флеше (PROGMEM).
 *   долговременное — настройки, одометр: меняются и переживают выключение.
 *                    hal_nvm.h. На ATmega328P это EEPROM.
 *
 * ЗАЧЕМ ЭТО НУЖНО. У ATmega328P 2 КБ RAM. Таблица дескрипторов параметров
 * (ADR-0005) занимает около 7 байт на параметр; при 35 параметрах это
 * 245 байт, то есть 12 % всей оперативной памяти под данные, которые
 * никогда не меняются. Во флеше те же 245 байт — меньше процента.
 *
 * ЕДИНСТВЕННОЕ МЕСТО ВНЕ HAL С ПЛАТФОРМЕННЫМ УСЛОВИЕМ. Макрос UTIL_ROM
 * обязан раскрываться в атрибут размещения там, где объявлены данные, —
 * спрятать это за вызовом функции нельзя. Поэтому здесь стоит #ifdef
 * по предикату компилятора __AVR__. Это не заголовок платформы, сторож
 * границ на него не среагирует, и назвать это вслух честнее, чем
 * оставить pgm_read_byte_near разбросанным по трём файлам, как было.
 *
 * Порт на другую платформу: если у неё единое адресное пространство
 * (STM32, ESP32), UTIL_ROM пуст, а чтение — обычное разыменование.
 * Код выше при этом не меняется вовсе.
 */
#pragma once

#include <stdint.h>

#ifdef __AVR__
/** Разместить данные в постоянной памяти вместо RAM. */
#  define UTIL_ROM __attribute__((__progmem__))
/**
 * @brief Строковый литерал в постоянной памяти
 *
 * Возвращает указатель, который можно читать только через util_rom_*.
 */
#  define UTIL_ROM_STR(s) (__extension__({ static const char c__[] UTIL_ROM = (s); &c__[0]; }))
#else
#  define UTIL_ROM
#  define UTIL_ROM_STR(s) (s)
#endif

/**
 * @brief Прочитать байт из постоянной памяти
 * @param addr Адрес, полученный от данных с атрибутом UTIL_ROM
 * @return Байт
 */
uint8_t util_rom_read_u8(const void *addr);

/**
 * @brief Прочитать 16-битное слово из постоянной памяти
 * @param addr Адрес
 * @return Слово
 */
uint16_t util_rom_read_u16(const void *addr);

/**
 * @brief Скопировать блок из постоянной памяти в RAM
 * @param dst Куда, в RAM
 * @param src Откуда, постоянная память
 * @param len Сколько байт
 */
void util_rom_read_block(void *dst, const void *src, uint8_t len);
