/**
 * @file hal_encoder.h
 * @brief HAL: измерение времени между импульсами энкодеров колёс
 *
 * INT0 (D2) — правое колесо
 * INT1 (D3) — левое колесо
 *
 * ADR-0023: скорость считается ТОЛЬКО по времени между импульсами.
 * Обработчик прерывания на каждом фронте берёт метку времени и
 * запоминает разность с предыдущей. Подсчёт импульсов остался, но он
 * питает одометр (пройденный путь), а не расчёт скорости.
 *
 * Реализация: hal_atmega328p.cpp
 */
#pragma once

#include <stdint.h>

/** Канал энкодера */
typedef enum {
    ENCODER_RIGHT = 0,  /**< INT0 (D2) */
    ENCODER_LEFT  = 1,  /**< INT1 (D3) */
    ENCODER_COUNT = 2
} encoder_channel_t;

/**
 * @brief Снимок состояния одного канала
 *
 * Все поля берутся за одну атомарную секцию, поэтому согласованы
 * между собой.
 */
typedef struct {
    uint32_t period_us;      /**< время между двумя последними импульсами, мкс */
    uint32_t last_pulse_us;  /**< метка времени последнего импульса */
    uint16_t pulses;         /**< импульсов с прошлого вызова (для одометра) */
    uint8_t  has_period;     /**< 1 — период измерен хотя бы раз с запуска */
} encoder_sample_t;

void hal_encoder_init(void);

/**
 * @brief Снять показания канала и обнулить счётчик импульсов
 *
 * Период и метка последнего импульса не обнуляются: они описывают
 * состояние колеса, а не накопленное с прошлого вызова. Обнуляется
 * только счётчик импульсов, чтобы одометр не считал их дважды.
 *
 * Частота вызова значения не имеет — расчёт от неё не зависит.
 *
 * @param ch  Канал энкодера
 * @param out Куда положить снимок; при неверном канале заполняется нулями
 */
void hal_encoder_take(encoder_channel_t ch, encoder_sample_t *out);

/**
 * @brief Сколько фронтов отброшено фильтром дребезга
 *
 * Фронт, пришедший раньше ENCODER_MIN_PERIOD_US после предыдущего,
 * физически невозможен и считается наводкой. Счётчик не обнуляется:
 * растущее значение означает проблему с проводкой или датчиком, и это
 * должно быть видно, а не потеряно (CLAUDE.md §7).
 */
uint16_t hal_encoder_glitch_count(encoder_channel_t ch);
