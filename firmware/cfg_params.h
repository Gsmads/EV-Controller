/**
 * @file cfg_params.h
 * @brief Реестр параметров настроек: одна охраняемая дверь для записи
 *
 * Решение ADR-0005. Дефект S-3 docs/AUDIT.md: запись настроек проверяла
 * только выход за границы структуры, поэтому `brake_rate_max = 0`
 * отключал тормоз и уходил в EEPROM.
 *
 * ОТКУДА БЕРУТСЯ ГРАНИЦЫ. Только из устройства системы, не из вкуса:
 *
 *   - АЦП десятибитный, значит сырые значения педалей 0…1023;
 *   - перечисление кривых отклика содержит три значения, значит 0…2;
 *   - каналов АЦП восемь, значит 0…7;
 *   - датчик тока ACS712-20A меряет до 20 А, значит пороги до 20000 мА;
 *   - темп торможения, равный нулю, означает отсутствие торможения —
 *     значит минимум единица.
 *
 * Где честной границы нет, стоит предел типа, и это отмечено в таблице
 * словом ТИП. Выдуманное «разумное» ограничение хуже отсутствующего: оно
 * выглядит проверкой, не будучи ей. Такие поля перечислены в docs/AUDIT.md
 * и сужаются после замеров на железе.
 *
 * ДВЕ ТАБЛИЦЫ, А НЕ ОДНА. Профилей режимов девять, полей в каждом десять.
 * Дескриптор занимает 16 байт (выравнивание int32). Описать 90 одинаковых
 * полей поимённо — это 123 дескриптора и 1968 байт флеша; описать поля
 * профиля один раз — 43 дескриптора и 688 байт, то есть 2,1 % флеша.
 * Экономия 1280 байт, поэтому смещение внутри массива вычисляется.
 *
 * Таблицы лежат в постоянной памяти (ADR-0021), поэтому наружу отдаётся
 * копия дескриптора, а не указатель на него.
 */
#pragma once

#include <stdint.h>
#include "cfg_settings.h"

/** Тип значения параметра. */
typedef enum {
    PARAM_U8  = 0,
    PARAM_U16 = 1,
    PARAM_I16 = 2
} param_type_t;

/** Свойства параметра. */
typedef enum {
    PARAM_FLAG_NONE     = 0,
    PARAM_FLAG_READONLY = 1 << 0,  /**< Запись отвергается всегда */
    PARAM_FLAG_ALLOW_FF = 1 << 1,  /**< Дополнительно допустимо 0xFF */
    PARAM_FLAG_TYPE_MAX = 1 << 2   /**< Границы — предел типа, не физика */
} param_flag_t;

/** Описание одного параметра. */
typedef struct {
    uint16_t id;      /**< Стабильный идентификатор, не смещение */
    uint16_t offset;  /**< Смещение: в settings_t либо в drive_profile_t */
    uint8_t  type;    /**< param_type_t */
    uint8_t  flags;   /**< param_flag_t */
    int32_t  min;
    int32_t  max;
} param_desc_t;

/** Результат проверки записи. */
typedef enum {
    PARAM_OK            = 0,
    PARAM_OUT_OF_BOUNDS = 1,  /**< Смещение выходит за структуру */
    PARAM_UNKNOWN       = 2,  /**< Смещение не соответствует ни одному полю */
    PARAM_SIZE_MISMATCH = 3,  /**< Размер не совпадает с размером поля */
    PARAM_READONLY      = 4,  /**< Поле не предназначено для записи */
    PARAM_OUT_OF_RANGE  = 5   /**< Значение вне допустимых границ */
} param_status_t;

/**
 * @brief Найти описание параметра по смещению в settings_t
 *
 * Смещение внутри массива профилей разбирается автоматически: индекс
 * профиля и поле вычисляются, возвращается описание поля профиля
 * со смещением, уже приведённым к settings_t.
 *
 * @param offset Смещение в settings_t
 * @param out    Куда скопировать описание
 * @return 1 — найдено, 0 — такого поля нет
 */
uint8_t cfg_params_find_by_offset(uint16_t offset, param_desc_t *out);

/**
 * @brief Найти описание параметра по идентификатору
 * @param id  Идентификатор
 * @param out Куда скопировать описание
 * @return 1 — найдено, 0 — нет
 */
uint8_t cfg_params_find_by_id(uint16_t id, param_desc_t *out);

/**
 * @brief Сколько параметров в реестре (без учёта повторов по профилям)
 * @return Число описаний
 */
uint8_t cfg_params_count(void);

/**
 * @brief Взять описание по порядковому номеру
 * @param index Номер, 0…cfg_params_count()-1
 * @param out   Куда скопировать
 * @return 1 — есть, 0 — номер за пределами
 */
uint8_t cfg_params_get(uint8_t index, param_desc_t *out);

/**
 * @brief Проверить значение по описанию
 * @param d     Описание
 * @param value Значение, приведённое к int32_t
 * @return param_status_t
 */
uint8_t cfg_params_check(const param_desc_t *d, int32_t value);

/**
 * @brief Разобрать сырые байты в значение по типу параметра
 * @param d    Описание
 * @param data Байты, младший первым
 * @param size Сколько байт пришло
 * @param out  Куда положить значение
 * @return param_status_t: PARAM_SIZE_MISMATCH, если размер не тот
 */
uint8_t cfg_params_decode(const param_desc_t *d, const void *data,
                          uint8_t size, int32_t *out);
