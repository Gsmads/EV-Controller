/**
 * @file svc_speed.h
 * @brief Сервис расчёта скорости колёс
 *
 * ADR-0023: скорость считается ТОЛЬКО по времени между импульсами
 * энкодера. Подсчёт импульсов за окно как способ измерения скорости
 * удалён — он давал квант 1,9 км/ч при 12 импульсах на оборот и такте
 * 10 Гц. Импульсы по-прежнему считаются, но питают одометр: путь — это
 * количество импульсов, а не время между ними.
 *
 * Каждое колесо обрабатывается независимо для будущего
 * torque vectoring / ABS.
 *
 * Параметры пересчёта берутся из cfg_board.h:
 *   ENCODER_PULSES_PER_REV — импульсов на оборот (уточнить экспериментально)
 *   WHEEL_DIAMETER_MM      — диаметр колеса в мм
 *
 * @version 2.0.0
 */
#pragma once
#include <stdint.h>

typedef enum {
    SPEED_WHEEL_LEFT  = 0,
    SPEED_WHEEL_RIGHT = 1,
    SPEED_WHEEL_COUNT = 2
} speed_wheel_t;

/**
 * @brief Что известно о колесе
 *
 * Три состояния, а не два, потому что «ноль» бывает разный
 * (CLAUDE.md §7). Пока не пришло ни одного импульса, стоящее колесо и
 * неподключённый датчик выглядят одинаково — и это должно быть видно.
 */
typedef enum {
    SPEED_NO_DATA = 0,  /**< измерений не было: стоим или датчика нет, различить нельзя */
    SPEED_STOPPED,      /**< измерения были, сейчас колесо не крутится */
    SPEED_MOVING        /**< есть свежий период, скорость измерена */
} speed_state_t;

/** Инициализация. Вызывает hal_encoder_init() */
void svc_speed_init(void);

/**
 * @brief Обновление: снять показания энкодеров, пересчитать скорость
 *
 * Частота вызова на результат не влияет — измерение опирается на метки
 * времени, а не на интервал между вызовами. Чем чаще вызывается, тем
 * свежее показания, и только.
 */
void svc_speed_update(void);

/** Что известно о колесе */
speed_state_t svc_speed_get_state(speed_wheel_t wheel);

/** Обороты колеса в минуту. 0, если состояние не SPEED_MOVING */
uint16_t svc_speed_get_rpm(speed_wheel_t wheel);

/**
 * @brief Средняя линейная скорость машины
 *
 * Усредняются скорости колёс, а не их периоды: скорость обратно
 * пропорциональна периоду, и среднее периодов дало бы не ту величину.
 * Учитываются только колёса в состоянии SPEED_MOVING.
 *
 * @return км/ч × 10 (для отображения формата XX.X)
 */
uint16_t svc_speed_get_kmh_x10(void);

/** Пройденный путь в метрах (одометр) */
uint32_t svc_speed_get_odometer_m(void);

/** Машина стоит? (ни одно колесо не в состоянии SPEED_MOVING) */
uint8_t svc_speed_is_stopped(void);

/** Сбросить одометр в 0 */
void svc_speed_reset_odometer(void);

/** Сколько фронтов отброшено фильтром дребезга на этом колесе */
uint16_t svc_speed_get_glitch_count(speed_wheel_t wheel);
