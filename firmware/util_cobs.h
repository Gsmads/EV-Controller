/**
 * @file util_cobs.h
 * @brief COBS: кодирование, убирающее нулевой байт из данных
 *
 * Consistent Overhead Byte Stuffing. Кодированные данные гарантированно
 * не содержат байта 0x00, поэтому 0x00 можно использовать как границу
 * кадра — и эта граница не может встретиться внутри кадра ни при каких
 * данных.
 *
 * Зачем это здесь (ADR-0024): прежний протокол искал начало кадра по
 * байту 0xAA, который в полезных данных встречается свободно. Парсер,
 * потерявший середину кадра, съедал начало следующего и терял его тоже
 * (дефект T-4). С COBS восстановление не требует угадывания: любой
 * встреченный 0x00 — конец единицы обмена, точка.
 *
 * Накладные расходы: +1 байт на кадр и ещё +1 на каждые 254 байта
 * данных. Для кадра протокола (не более 63 байт) это ровно один байт.
 *
 * Модуль платформонезависимый и проверяется на десктопе.
 */
#pragma once
#include <stdint.h>

/**
 * @brief Закодировать блок
 *
 * @param src Исходные данные (может содержать любые байты, включая 0x00)
 * @param len Длина исходных данных, 0..254
 * @param dst Куда писать; результат не содержит 0x00
 * @param cap Ёмкость приёмника. Тип шире uint8_t намеренно: при len = 254
 *            результат занимает 255 байт, и ёмкость 256 должна быть
 *            выразимой, иначе sizeof() молча усекался бы.
 * @return Длина результата, либо -1 при нехватке места или неверных
 *         аргументах. Пустой вход даёт результат длиной 1 байт.
 */
int16_t util_cobs_encode(const uint8_t *src, uint8_t len,
                         uint8_t *dst, uint16_t cap);

/**
 * @brief Раскодировать блок
 *
 * Разделитель 0x00 в src НЕ входит — передавать только байты между
 * разделителями.
 *
 * @param src Закодированные данные. Байт 0x00 внутри означает, что это
 *            не кадр: такой вход отвергается, а не разбирается.
 * @param len Длина закодированных данных
 * @param dst Куда писать результат. Допускается dst == src: разбор
 *            идёт на месте. Выход всегда короче входа, а записи всегда
 *            попадают в уже прочитанные байты - свойство проверяется
 *            тестом test_decode_in_place.
 * @param cap Ёмкость приёмника
 * @return Длина результата, либо -1 если данные не являются корректным
 *         COBS (нулевой байт внутри, оборванная группа) или не влезли.
 */
int16_t util_cobs_decode(const uint8_t *src, uint8_t len,
                         uint8_t *dst, uint16_t cap);
