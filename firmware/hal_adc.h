/**
 * @file hal_adc.h
 * @brief HAL: аналого-цифровое преобразование (АЦП)
 *
 * Платформонезависимый интерфейс для чтения аналоговых входов.
 * На ATmega328P: 10-бит АЦП, 8 каналов (A0–A7).
 *
 * Реализация: hal_atmega328p.c
 */
#pragma once

#include <stdint.h>

/**
 * @brief Инициализация АЦП
 * Настраивает прескалер, опорное напряжение.
 */
void hal_adc_init(void);

/**
 * @brief Чтение аналогового канала (блокирующее, ~104 мкс на ATmega328P)
 * @param channel Номер канала (0–7)
 * @return 10-битное значение (0–1023)
 */
uint16_t hal_adc_read(uint8_t channel);
