/**
 * @file hal_adc.h
 * @brief HAL: аналого-цифровое преобразование (АЦП)
 *
 * Платформонезависимый интерфейс для чтения аналоговых входов.
 * На ATmega328P: 10-бит АЦП, 8 каналов (A0–A7).
 *
 * Реализация: hal_atmega328p.c
 */
#pragma once

#include <stdint.h>

/**
 * @brief Инициализация АЦП
 * Настраивает прескалер, опорное напряжение.
 */
void hal_adc_init(void);

/**
 * @brief Чтение аналогового канала (блокирующее, ~104 мкс на ATmega328P)
 *
 * Принимается ТОЛЬКО номер канала АЦП, 0…7 — тот, что кладётся в ADMUX.
 * Номера выводов платы (A0 = 14 и далее) здесь недопустимы: раньше функция
 * угадывала нумерацию по величине числа, и это было источником ошибок,
 * а не удобством. Карта каналов живёт в настройках, ADR-0009.
 *
 * @param channel Номер канала АЦП, 0…7
 * @return 10-битное значение (0–1023); при недопустимом канале — 0
 *
 * @note Почему при отказе возвращается 0, а не признак ошибки. Это значение
 *       уходит в калибровочную формулу педали. Любой «признак» вне диапазона
 *       (0xFFFF и подобные) прошёл бы через util_map_u16 как значение выше
 *       верхней точки и дал бы полный газ. Ноль означает «педаль отпущена» —
 *       безопасный исход. Сам отказ не молчаливый: его считает
 *       hal_adc_bad_channel_count().
 */
uint16_t hal_adc_read(uint8_t channel);

/**
 * @brief Сколько раз запрашивался недопустимый канал АЦП
 *
 * У отказа должно быть имя и счётчик (CONVENTIONS.md §10). Ненулевое
 * значение означает ошибку в карте каналов, а не помеху на входе.
 *
 * @return Число обращений с каналом вне диапазона 0…7
 */
uint16_t hal_adc_bad_channel_count(void);
