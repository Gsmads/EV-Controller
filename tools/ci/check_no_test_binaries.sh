#!/usr/bin/env bash
#
# Сторож: в tests/ под контролем версий лежат только исходники.
#
# Задача 0.2.6 из docs/SLICE_0_PLAN.md. Критерий: `git ls-files tests/` возвращает
# только Makefile, README.md и файлы test_*.c / test_*.cpp / test_*.h.
#
# Почему смотрим индекс git, а не каталог: собранные, но не добавленные в индекс
# бинарники проверку проходят — и это правильно. `make run` их создаёт, и падать
# на них означало бы падать всегда. Мешают они только тогда, когда попадают
# в коммит; ровно это здесь и ловится.
#
# Чего сторож НЕ покрывает — честно:
#   - бинарники вне tests/: артефакты Arduino IDE, содержимое tools/ он не смотрит;
#   - файл, попавший в историю ДО появления сторожа: он ловит текущее состояние
#     индекса, историю не переписывает и о ней не знает;
#   - содержимое файлов: решение принимается по имени. Скомпилированный бинарник,
#     названный tests/test_foo.c, пройдёт;
#   - подкаталоги tests/ он допускает только с теми же именами файлов — если
#     появится tests/fixtures/, сторож на неё упадёт, и это осознанно: пусть
#     расширение структуры будет явным решением, а не побочным эффектом;
#   - .gitignore сторожа не подменяет: файл, добавленный через `git add -f`,
#     в .gitignore остаётся скрытым, но в индексе виден — сторож его поймает.
#
# Запуск: tools/ci/check_no_test_binaries.sh (из любого каталога репозитория)

set -euo pipefail

cd "$(dirname "$0")/../.."

ALLOWED='^tests/(Makefile|README\.md|test_[A-Za-z0-9_]+\.(c|cpp|h))$'

tracked=$(git ls-files tests/)
if [ -z "$tracked" ]; then
    echo "Сторож 0.2.6: каталог tests/ пуст или не под контролем версий." >&2
    exit 1
fi

unexpected=$(echo "$tracked" | grep -Ev "$ALLOWED" || true)

if [ -n "$unexpected" ]; then
    echo "Сторож 0.2.6: в tests/ под контролем версий лишние файлы:" >&2
    echo "$unexpected" | sed 's/^/    /' >&2
    echo >&2
    echo "Ожидаются только Makefile, README.md и исходники test_*.c / test_*.cpp / test_*.h." >&2
    echo "Если это собранный бинарник:" >&2
    echo "    cd tests && make clean" >&2
    echo "    git rm --cached <файл>" >&2
    echo "Основание: docs/SLICE_0_PLAN.md, задача 0.2.6." >&2
    exit 1
fi

echo "Сторож 0.2.6: в tests/ только исходники, $(echo "$tracked" | wc -l) файлов."
